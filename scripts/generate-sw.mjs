import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..", "dist");

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(entries.map(async (entry) => {
    const full = join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  }));
  return files.flat();
}

// Precache published application assets, not the user's PDF documents.
const files = (await walk(root))
  .filter((file) => !file.endsWith(sep + "sw.js"))
  .sort();
const hash = createHash("sha256");
const paths = ["./"];
for (const file of files) {
  const path = relative(root, file).split(sep).join("/");
  hash.update(path);
  hash.update(await readFile(file));
  paths.push("./" + path);
}
const version = hash.digest("hex").slice(0, 12);

const serviceWorker = `/* Generated by scripts/generate-sw.mjs; do not edit dist/sw.js directly. */
const CACHE = "pdf-cutter-app-%%VERSION%%";
const APP_SHELL = %%ASSETS%%;
const SCOPE = new URL(self.registration.scope);

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await cache.addAll(APP_SHELL.map((path) => new URL(path, SCOPE)));
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((key) => key.startsWith("pdf-cutter-app-") && key !== CACHE)
      .map((key) => caches.delete(key)));
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== "GET" || url.origin !== SCOPE.origin ||
      !url.pathname.startsWith(SCOPE.pathname)) return;

  if (request.mode === "navigate") {
    event.respondWith((async () => {
      try {
        const response = await fetch(request);
        if (response.ok) {
          const cache = await caches.open(CACHE);
          await cache.put(new URL("./", SCOPE), response.clone());
        }
        return response;
      } catch {
        const cache = await caches.open(CACHE);
        return (await cache.match(new URL("./", SCOPE))) ||
          (await cache.match(new URL("./index.html", SCOPE))) ||
          Response.error();
      }
    })());
    return;
  }

  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const cached = await cache.match(request);
    if (cached) return cached;
    const response = await fetch(request);
    if (response.ok && response.type === "basic") {
      await cache.put(request, response.clone());
    }
    return response;
  })());
});
`.replace("%%VERSION%%", version).replace("%%ASSETS%%", JSON.stringify(paths));

await writeFile(join(root, "sw.js"), serviceWorker, "utf8");
console.log("Generated offline-ready service worker:", version, "with", paths.length, "app assets");
